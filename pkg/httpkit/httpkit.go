// Package httpkit collects net/http presets for building services: ready-made
// handlers and the shared conventions they rely on. It has no third-party
// dependencies.
//
// # Sub-packages
//
// Each handler is its own package; import the one you need directly. This
// package does not re-export them, so the import path is the discovery path:
//
//   - gorontalo/pkg/httpkit/healthcheck — health, liveness, and readiness
//     endpoints for orchestrators such as Kubernetes.
//   - gorontalo/pkg/httpkit/stdwrapper — adapts application handlers to a
//     standard request/response contract (request ID, response envelope,
//     error-code header, logging, panic recovery).
//
// New presets are added as sibling sub-packages under gorontalo/pkg/httpkit and
// listed here, so this comment stays the index of what the kit offers.
//
// # Shared contracts
//
// This package itself holds only what is shared across those sub-packages or
// useful without any of them, not forwarded copies of their symbols.
//
// It re-exports the standard header names the handlers use so callers can
// reference them without importing a specific handler sub-package. They are
// grouped under the Headers namespace:
//
//	req.Header.Get(httpkit.Headers.RequestID)
//	resp.Header.Get(httpkit.Headers.ErrorCode)
//
// It also provides DecodeJSON, a generic helper that decodes a request body
// into a struct and reports failures as a 400 standard error:
//
//	body, err := httpkit.DecodeJSON[CreateUser](r)
package httpkit

import "gorontalo/pkg/httpkit/stdwrapper"

// headerNames groups the standard HTTP header names used across httpkit. The
// single exported value Headers is the instance callers reference; the type is
// unexported so the set stays closed.
type headerNames struct {
	// RequestID is the request/response header carrying the request ID
	// (generated by stdwrapper when absent on the request).
	RequestID string
	// ErrorCode is the response header carrying the application-level error
	// code, which is distinct from the HTTP status.
	ErrorCode string
}

// Headers holds the standard HTTP header names used by httpkit's handlers.
// Reference a field rather than hardcoding the string, e.g.
// httpkit.Headers.RequestID.
var Headers = headerNames{
	RequestID: stdwrapper.HeaderRequestID,
	ErrorCode: stdwrapper.HeaderErrorCode,
}
